/** Every format in `family`, or undefined for an unknown family. */
export function familyMembers(family: string): readonly string[] | undefined {
	return SOURCE_FAMILIES[family];
}

/** Every target a source family can reach: its groups expanded, plus its single formats. */
export function reachableTargets(family: string): readonly string[] {
	const route = ROUTES[family];
	if (route === undefined) return [];
	const targets = new Set<string>(route.formats);
	for (const group of route.groups) for (const format of TARGET_GROUPS[group] ?? []) targets.add(format);
	return [...targets];
}

/**
 * Compact conversion guide for the system prompt: families, target groups, the
 * route table, and the rules that decide whether a chain is needed.
 */
export function renderConversionGuide(): string {
	const lines: string[] = [];
	lines.push("Source families (format ids; a family is one row in the route table):");
	for (const [family, members] of Object.entries(SOURCE_FAMILIES)) lines.push(`- ${family}: ${members.join(" ")}`);
	lines.push("", "Target groups used by the routes:");
	for (const [group, members] of Object.entries(TARGET_GROUPS)) lines.push(`- ${group}: ${members.join(" ")}`);
	lines.push(
		"",
		"Routes: every format in the source family converts DIRECTLY to every format in each listed group, plus the single formats after `+` (never to itself):",
	);
	for (const [family, route] of Object.entries(ROUTES)) {
		const extra = route.formats.length > 0 ? ` + ${route.formats.join(" ")}` : "";
		lines.push(`- ${family} -> ${route.groups.join(", ")}${extra}`);
	}
	lines.push(
		"",
		"Planning rules:",
		"- Check the route table before calling a tool; when the target is listed, call convert_files directly. For a format that is not in a family above, or to confirm one pair, call list_file_conversions with the source format.",
		"- If the pair has no direct route, chain two conversions through a format both sides reach (for example mp4 -> mp3 is direct, but audio -> text has no route at all: Filee never transcribes). Convert the intermediate into a scratch folder with outputDir and report the final file only.",
		"- Audio, fonts, subtitles, and archives only convert within their own family (archives: zip 7z tar tgz tbz2 txz; gz bz2 xz are single-file compressors). Many archive and document formats are read-only sources (rar, iso, jar, doc-era formats such as wps and wpd): they can be converted FROM, not TO.",
		"- Targets such as doc, ppt, xls, odt, odp, mobi, azw3, eps, ps, emf, wmf, and odg rely on an engine (LibreOffice, calibre, Ghostscript) that Filee downloads on the first conversion that needs it (hundreds of MB, once). On Linux Filee has no Ghostscript or LibreOffice download: it uses ones already installed, and the call fails naming the missing engine.",
		"- Text-bearing targets keep text (pdf, docx, hwpx, md, html, epub); image and video targets from documents are rendered pages. Images become documents as a picture, not as recognized text (no OCR).",
	);
	return lines.join("\n");
}
